  function attachModalWindowListeners() {
    // Bind Tab Bar Buttons inside Modal Header
    document.querySelectorAll('.modal-tab-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation(); // Stop event bubbling so modal backdrop click listener DOES NOT exit/close the window!
        const tabName = btn.getAttribute('data-tab');
        if (currentProject) {
          renderModalTabContent(tabName);
        }
      });
    });

    document.querySelectorAll('[data-modal-type]').forEach(elem => {
      elem.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();

        const projectId = elem.getAttribute('data-project');
        const modalType = elem.getAttribute('data-modal-type');
        let project = projectsMap[projectId] || projectsData.find(p => p.id === projectId);

        if (!project || !itemModal) return;

        currentProject = project;

        if (itemModalCategory) itemModalCategory.textContent = project.category;
        if (itemModalTitle) itemModalTitle.textContent = project.title;
        if (itemModalCounter) itemModalCounter.textContent = '';

        renderModalTabContent(modalType);
        openModalWindow();
      });
    });

    document.querySelectorAll('.live-edit-card-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        const projId = btn.getAttribute('data-project');
        if (typeof window.openAdminEditModal === 'function') {
          window.openAdminEditModal(projId);
        }
      });
    });

    document.querySelectorAll('.admin-delete-proj-btn').forEach(btn => {
      btn.addEventListener('click', async (e) => {
        e.preventDefault();
        e.stopPropagation();
        const projId = btn.getAttribute('data-project');
        const project = projectsMap[projId];
        if (!project) return;

        if (confirm(`Are you sure you want to delete "${project.title}" from your portfolio?`)) {
          // 1. Immediately delete locally in memory & projectsMap
          const idx = projectsData.findIndex(p => p.id === projId);
          if (idx >= 0) projectsData.splice(idx, 1);
          delete projectsMap[projId];

          // 2. Persist updated list to localStorage
          if (typeof saveProjectsToStorage === 'function') {
            saveProjectsToStorage();
          }

          // 3. Immediately re-render project cards in UI
          if (typeof renderProjectCards === 'function') {
            renderProjectCards();
          }

          showToast(`✓ Project "${project.title}" deleted from portfolio.`);

          // 4. Asynchronously sync deletion to Supabase
          const client = getSupabaseClient();
          if (client) {
            try {
              await Promise.all([
                client.from('projects').delete().eq('id', projId),
                client.from('site_content').upsert([{ key: 'projects_backup', value: projectsData, updated_at: new Date().toISOString() }])
              ]);
            } catch (err) {
              console.warn('Supabase delete background notice:', err);
            }
          }
        }
      });
    });


  }

