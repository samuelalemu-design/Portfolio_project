    // Inline Form Submit Event (Add or Update Project in Supabase & Local Memory)
    if (inlineForm) {
      inlineForm.addEventListener('submit', async (e) => {
        e.preventDefault();
        const submitBtn = inlineForm.querySelector('button[type="submit"]');
        const originalBtnHTML = submitBtn ? submitBtn.innerHTML : 'Save Project';

        if (submitBtn) {
          submitBtn.disabled = true;
          submitBtn.innerHTML = `<span class="btn-spinner"></span> Saving Project...`;
        }

        await new Promise(r => setTimeout(r, 0));

        const editId = document.getElementById('inline-edit-proj-id').value;
        const title = document.getElementById('inline-edit-proj-title').value.trim();
        const category = document.getElementById('inline-edit-proj-category').value;
        const overview = document.getElementById('inline-edit-proj-overview').value.trim();
        const rawSpecs = document.getElementById('inline-edit-proj-specs').value.trim();
        const rawTags = document.getElementById('inline-edit-proj-tags').value.trim();

        const materialsVal = document.getElementById('inline-edit-proj-materials') ? document.getElementById('inline-edit-proj-materials').value.trim() : '';
        const manufacturingVal = document.getElementById('inline-edit-proj-manufacturing') ? document.getElementById('inline-edit-proj-manufacturing').value.trim() : '';
        const webglVal = document.getElementById('inline-edit-proj-webgl') ? document.getElementById('inline-edit-proj-webgl').value.trim() : '';
        const pdfVal = document.getElementById('inline-edit-proj-pdf') ? document.getElementById('inline-edit-proj-pdf').value.trim() : '';

        const specs = rawSpecs ? rawSpecs.split('\n').map(s => s.trim()).filter(Boolean) : [];
        const dfmTags = rawTags ? rawTags.split(',').map(t => t.trim()).filter(Boolean) : [category];

        const heroImage = currentEditHeroImage || (currentEditRenderings.length > 0 ? currentEditRenderings[0] : 'assets/projects/p1/hero.jpg');
        
        let renderings = [...currentEditRenderings];
        if (heroImage && !renderings.includes(heroImage)) {
          renderings.unshift(heroImage);
        }

        const projId = editId || `proj_${Date.now()}`;
        const projCreatedAt = (editId && projectsMap[editId] && projectsMap[editId].created_at) ? projectsMap[editId].created_at : new Date().toISOString();

        // Formatted Local Project Object
        const localProject = {
          id: projId,
          number: (editId && projectsMap[editId] && projectsMap[editId].number) ? projectsMap[editId].number : projectsData.length + 1,
          title: title,
          category: category,
          overview: overview,
          description: overview,
          specs: specs,
          dfm_tags: dfmTags,
          dfmTags: dfmTags,
          image: heroImage,
          renderings: renderings,
          gallery: renderings,
          allGalleryImages: renderings,
          drawings: currentEditDrawings,
          attachments: currentEditDrawings,
          materials: materialsVal,
          manufacturing_process: manufacturingVal,
          webgl_url: webglVal,
          pdf_url: pdfVal,
          created_at: projCreatedAt,
          annotations: [],
          imageTextOverlays: {}
        };

        // 1. Immediately update local in-memory arrays & projectsMap
        projectsMap[projId] = localProject;
        const existingIdx = projectsData.findIndex(p => p.id === projId);
        if (existingIdx >= 0) {
          projectsData[existingIdx] = localProject;
        } else {
          projectsData.unshift(localProject);
        }

        // 2. Persist to localStorage fallback
        if (typeof saveProjectsToStorage === 'function') {
          saveProjectsToStorage();
        }

        // 3. Immediately re-render project cards in UI & Admin lists
        if (typeof renderProjectCards === 'function') {
          renderProjectCards();
        }

        // 4. Mark draft committed
        hasUnsavedChanges = false;

        // 5. Asynchronously sync updated project list directly to Supabase Cloud
        const client = getSupabaseClient();
        if (client) {
          try {
            await client.from('site_content').upsert([{ key: 'projects_backup', value: projectsData, updated_at: new Date().toISOString() }]);
            showToast("✓ Project saved directly to Supabase cloud database!");
          } catch (err) {
            console.error('Supabase Cloud Sync Exception:', err);
            showToast("✓ Project saved!", false);
          }
        } else {
          showToast("✓ Project added to project list successfully!");
        }

        if (submitBtn) {
          submitBtn.disabled = false;
          submitBtn.innerHTML = originalBtnHTML;
        }

        closeInlineProjectEditor();
      });
    }




